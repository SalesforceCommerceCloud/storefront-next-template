/** @sfdc-extension-file SFDC_EXT_STORE_LOCATOR */
import { applyUrlConfig } from '@salesforce/storefront-next-runtime/site-context';
import type {
    CompiledRouteManifest,
    CompiledRouteMetadata,
} from '@salesforce/storefront-next-runtime/routing/compiled-routes';

const manifest: CompiledRouteManifest = { routes: {} };
/** Test-only metadata generated by the real SDK compiler, with explicit document/resource exports. */
export function setRecoveryManifest(
    urlConfig: NonNullable<Parameters<typeof applyUrlConfig>[0]['urlConfig']> = {
        prefix: '/:siteId/:localeId?',
        excludeRoutes: ['/resource/**', '/action/**'],
    },
    /** Add a document splat like routes/_empty.$.tsx, so unknown paths win a document route (renders 404). */
    { catchAll = false }: { catchAll?: boolean } = {}
) {
    const sources = [
        { id: 'home', index: true, file: 'home.tsx' },
        ...[
            'cart',
            'cart/details',
            'search',
            'category/*',
            'c/*',
            'p/*',
            'account',
            'account/store-preferences',
            'error-page',
        ].map((path) => ({ id: `document-${path}`, path, file: 'document.tsx' })),
        ...(catchAll ? [{ id: 'document-*', path: '*', file: 'document.tsx' }] : []),
        ...[
            'resource/auth-recovery',
            'resource/basket',
            'action/login',
            'action/set-selected-store',
            'action/save-default-store',
        ].map((path) => ({
            id: `resource-${path}`,
            path,
            file: 'resource.ts',
        })),
    ];
    const routes: Record<string, CompiledRouteMetadata> = { root: { id: 'root', path: '', isDocument: true } };
    function add(entries: ReturnType<typeof applyUrlConfig>, parentId = 'root') {
        for (const entry of entries) {
            if (!entry.id) throw new Error('Fixture route requires an ID');
            routes[entry.id] = {
                id: entry.id,
                parentId,
                path: entry.path,
                index: entry.index,
                caseSensitive: entry.caseSensitive,
                isDocument: entry.file !== 'resource.ts',
            };
            if (entry.children) add(entry.children, entry.id);
        }
    }
    add(urlConfig.prefix ? applyUrlConfig({ routes: sources, urlConfig, wrapperFile: 'wrapper.tsx' }) : sources);
    // New identity resets the SDK WeakMap cache between fixture configurations.
    manifest.routes = routes;
    return manifest;
}
setRecoveryManifest();
export default manifest;
